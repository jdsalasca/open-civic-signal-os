#!/usr/bin/env node
// Captures the evidence a trust incident needs, before anyone tries to fix it.
//
// The triage protocol (docs/TRUST_INCIDENT_TRIAGE.md) says: capture first, fix second, because a fix
// changes the state the capture was meant to preserve. Within an hour "what did the ranking look
// like when the complaint arrived" is unanswerable without this file.
//
// What it records is deliberately the set of things this platform later cannot reconstruct:
//   - the formula version in force, because a version can be superseded but not recovered
//   - a hash of the current ordering, so a later claim about it is checkable
//   - freshness per surface, because "silent since when" is the first question asked
//   - counts, so a change is a number rather than an impression
//
// Usage:
//   npm run incident:capture -- --label "Backlog showed stale ranks for W13"
//   npm run incident:capture -- --label "..." --api http://localhost:8080 --out docs/incidents
//
// Exit codes: 0 captured, 1 could not capture (which is itself worth knowing before you start).

import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

const args = parseArgs(process.argv.slice(2));

if (args.help || args.h) {
  printUsage();
  process.exit(0);
}

if (!args.label || !String(args.label).trim()) {
  fail('--label is required. An incident bundle without a description is unfindable later.');
}

const base = (args.api ?? process.env.API_BASE_URL ?? 'http://localhost:8080').replace(/\/$/, '');
const outDir = args.out ?? 'docs/incidents';
const capturedAt = new Date().toISOString();

const bundle = {
  label: String(args.label).trim(),
  capturedAt,
  api: base,
  schemaVersion: 'v1',
  // Each probe records either its payload or why it failed. A probe that silently omits itself
  // would make the bundle look complete when it is not.
  probes: {},
};

await probe('formula', `${base}/api/signals/formula`, (body) => ({
  version: body?.version ?? null,
  formula: body?.formula ?? null,
  effectiveFrom: body?.effectiveFrom ?? null,
  cappedFactors: body?.cappedFactors ?? null,
  changeNote: body?.changeNote ?? null,
}));

await probe('meta', `${base}/api/signals/meta`, (body) => ({
  totalSignals: body?.totalSignals ?? null,
  unresolvedSignals: body?.unresolvedSignals ?? null,
  lastUpdatedAt: body?.lastUpdatedAt ?? null,
  criticalScoreThreshold: body?.criticalScoreThreshold ?? null,
}));

await probe('ranking', `${base}/api/signals/prioritized?page=0&size=50`, (body) => {
  const content = Array.isArray(body?.content) ? body.content : [];
  if (content.length === 0) {
    return { note: 'ranking returned zero rows; the ordering hash below is over an empty list and proves nothing', entryCount: 0, orderingHash: null };
  }
  const canonical = content.map((entry) => `${entry.id}:${entry.priorityScore}`).join('\n');
  return {
    entryCount: content.length,
    totalElements: body?.totalElements ?? null,
    orderingHash: createHash('sha256').update(canonical, 'utf8').digest('hex'),
    topTitles: content.slice(0, 5).map((entry) => entry.title),
  };
});

await collectFreshness();

bundle.notes = [
  'Captured before any fix. Do not edit this file; add a separate record if something changes.',
  'The ordering hash covers id and score only. It is what lets a later claim about the ranking be checked.',
  'A probe that failed is recorded as failed rather than omitted, so an incomplete bundle is visible as incomplete.',
];

await mkdir(outDir, { recursive: true });
const slug = String(args.label)
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '')
  .slice(0, 60);
const stamp = capturedAt.replace(/[:.]/g, '-');
const file = path.join(outDir, `${stamp}-${slug}.json`);
await writeFile(file, `${JSON.stringify(bundle, null, 2)}\n`, 'utf8');

const failed = Object.values(bundle.probes).filter((probe) => probe.status !== 'captured').length;
console.log(`Incident bundle written: ${file}`);
console.log(`  probes captured: ${Object.keys(bundle.probes).length - failed}`);
if (failed > 0) {
  console.log(`  probes FAILED:   ${failed}  <-- the bundle is incomplete, say so in the incident record`);
}

async function collectFreshness() {
  // Freshness is per community and needs membership, so the global view is attempted and its
  // failure recorded rather than treated as "no staleness anywhere".
  await probe('freshness', `${base}/api/community/freshness?allowGlobal=true`, (body) => {
    const reports = Array.isArray(body) ? body : [];
    return {
      communities: reports.length,
      staleSurfaces: reports.flatMap((report) =>
        (report.sources ?? [])
          .filter((source) => source.verdict === 'STALE' || source.verdict === 'DORMANT')
          .map((source) => `${report.communityName ?? report.communityId}:${source.key}:${source.verdict}`),
      ),
    };
  });
}

async function probe(name, url, extract) {
  try {
    const response = await fetch(url, { headers: { accept: 'application/json' } });
    if (!response.ok) {
      bundle.probes[name] = {
        status: 'failed',
        httpStatus: response.status,
        reason: `${response.status} ${response.statusText}`,
        note: 'This value could not be captured. State that in the incident record.',
      };
      return;
    }
    const body = await response.json();
    bundle.probes[name] = { status: 'captured', ...extract(body) };
  } catch (error) {
    bundle.probes[name] = {
      status: 'failed',
      reason: error.message,
      note: 'The API could not be reached. If it is down, that is itself part of the incident.',
    };
  }
}

function parseArgs(argv) {
  const parsed = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === '--help' || token === '-h') {
      parsed.help = true;
      continue;
    }
    if (!token.startsWith('--')) {
      fail(`Unexpected argument "${token}". Use --key value pairs; see --help.`);
    }
    const key = token.slice(2);
    const value = argv[i + 1];
    if (value === undefined || value.startsWith('--')) {
      // A flag may legitimately take no value only for --help, handled above.
      fail(`Missing value for --${key}.`);
    }
    parsed[key] = value;
    i += 1;
  }
  return parsed;
}

function printUsage() {
  console.log(`Capture a trust-incident evidence bundle.

  --label "<text>"   Short description. Required; an unlabelled bundle is unfindable later.
  --api <url>        API base URL. Defaults to $API_BASE_URL or localhost:8080.
  --out <dir>        Where to write the bundle. Defaults to docs/incidents.
  --help             Show this message.

Exit 0 means a bundle was written. Exit 1 means nothing was written, which is worth knowing
before you start investigating.`);
}

function fail(message) {
  console.error(`incident:capture: ${message}`);
  process.exit(1);
}